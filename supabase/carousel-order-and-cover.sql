begin;
set local lock_timeout = '5s';

alter table public.qmargin_b74_carousels
  add column cover_media_id uuid,
  add constraint qmargin_b74_carousel_cover_member
    foreign key (id, cover_media_id)
    references public.qmargin_b74_carousel_photos (carousel_id, media_id)
    on delete set null (cover_media_id);
grant update (cover_media_id) on public.qmargin_b74_carousels to authenticated;

alter table public.qmargin_b74_carousel_photos alter column position set generated by default;

create function qmargin_b74_private.move_carousel_photo(p_carousel uuid, p_id uuid, p_direction integer)
returns boolean language plpgsql security definer set search_path = '' as $$
declare
  original bigint;
  neighbor record;
begin
  if not qmargin_b74_private.carousel_admin() then raise insufficient_privilege; end if;
  if p_direction is null or p_direction not in (-1, 1) then raise invalid_parameter_value; end if;
  -- Serialize moves within a carousel. Image and cover changes keep their own row locks.
  perform pg_advisory_xact_lock(hashtextextended(p_carousel::text, 0));
  select position into original from public.qmargin_b74_carousel_photos
    where carousel_id = p_carousel and media_id = p_id for no key update;
  if not found then return false; end if;

  if p_direction = -1 then
    select media_id, position into neighbor from public.qmargin_b74_carousel_photos
      where carousel_id = p_carousel and position < original order by position desc limit 1 for no key update;
  else
    select media_id, position into neighbor from public.qmargin_b74_carousel_photos
      where carousel_id = p_carousel and position > original order by position limit 1 for no key update;
  end if;
  if not found then return false; end if;

  update public.qmargin_b74_carousel_photos
    set position = case when media_id = p_id then neighbor.position else original end
    where carousel_id = p_carousel and media_id in (p_id, neighbor.media_id);
  return true;
end;
$$;

create function public.qmargin_b74_move_carousel_photo(p_carousel uuid, p_id uuid, p_direction integer)
returns boolean language sql set search_path = '' as $$
  select qmargin_b74_private.move_carousel_photo(p_carousel, p_id, p_direction);
$$;
revoke all on function qmargin_b74_private.move_carousel_photo(uuid, uuid, integer),
  public.qmargin_b74_move_carousel_photo(uuid, uuid, integer) from public, anon, authenticated;
grant execute on function qmargin_b74_private.move_carousel_photo(uuid, uuid, integer),
  public.qmargin_b74_move_carousel_photo(uuid, uuid, integer) to authenticated;

notify pgrst, 'reload schema';
commit;
